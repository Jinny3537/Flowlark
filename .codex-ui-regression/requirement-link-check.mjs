import assert from 'node:assert/strict';
import { chromium } from '/Users/beluga/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import { newHub, html, cleanup } from '../test/helpers.js';
import { startServer } from '../src/server/index.js';
const { root, hub } = newHub();
hub.createProject({ name: '关联验证', code: 'links' });
hub.createRequirement({ code: 'REQ-LINK', title: '统一需求记录', description: '来自需求模块' });
hub.addVersion('links', { versionNo: 'v1', title: '测试版本', html: html() });
const server = await startServer(root, { port: 0, previewPort: 0 });
const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto(`http://127.0.0.1:${server.port}/#/projects/links/versions/v1?tab=reqs`);
  await page.waitForLoadState('networkidle');
  await page.getByRole('button', { name: /管理关联需求/ }).click();
  await page.getByRole('combobox', { name: '从需求模块选择' }).fill('统一需求');
  await page.getByText('REQ-LINK · 统一需求记录', { exact: true }).click();
  await page.getByRole('button', { name: '移除需求 REQ-LINK', exact: true }).waitFor();
  assert.equal(await page.getByRole('combobox', { name: '从需求模块选择' }).inputValue(), '');
  await page.getByRole('button', { name: '找不到需求？手动录入' }).click();
  await page.getByRole('button', { name: '添加到已选列表' }).click();
  await page.getByText(/请填写有效编号/).waitFor();
  await page.getByRole('textbox', { name: '手动录入需求编号', exact: true }).fill('REQ-LINK');
  await page.getByRole('button', { name: '添加到已选列表' }).click();
  await page.getByText('该需求已在已选列表中，无需重复添加').waitFor();
  await page.getByRole('dialog').getByRole('button', { name: /取.*消/ }).click();
  await page.screenshot({ path: '/tmp/flowlark-requirement-picker.png', fullPage: true });
  await page.getByRole('button', { name: '保存关联需求' }).click();
  await page.getByRole('link', { name: '查看需求' }).waitFor();
  assert.equal(hub.getVersion('links', 'v1').requirements[0].code, 'REQ-LINK');
  assert.equal(hub.getRequirement('REQ-LINK').versions.length, 1);
  assert.equal(hub.listRequirements().length, 1);
  await page.getByRole('button', { name: /管理关联需求/ }).click();
  await page.getByRole('button', { name: '移除需求 REQ-LINK', exact: true }).click();
  await page.getByRole('button', { name: '取消编辑' }).click();
  await page.getByRole('link', { name: '查看需求' }).waitFor();
  assert.equal(hub.getRequirement('REQ-LINK').versions.length, 1);
  await page.getByRole('link', { name: '查看需求' }).click();
  await page.getByRole('heading', { name: '统一需求记录', exact: true }).waitFor();
  await page.getByRole('tab', { name: '关联版本（1）' }).click();
  await page.getByRole('button', { name: /links \/ v1/ }).waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS: 搜索选择已有需求、保存关联、无重复实体、双向详情导航');
} finally {
  await browser.close();
  await server.close();
  cleanup(root);
}
