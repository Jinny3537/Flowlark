import assert from 'node:assert/strict'
import { chromium } from '/Users/beluga/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs'
import { newHub, html, cleanup } from '../test/helpers.js'
import { startServer } from '../src/server/index.js'
const { root, hub } = newHub()
hub.createProject({ name: '导航验证项目', code: 'navigation' })
hub.addVersion('navigation', { versionNo: 'v1.0', title: '开发基线', html: html('基线原型内容') })
hub.setBaseline('navigation', 'v1.0')
hub.addVersion('navigation', { versionNo: 'v1.1', title: '待评审新版', html: html('新版原型内容') })
const server = await startServer(root, { port: 0, previewPort: 0 })
const base = `http://127.0.0.1:${server.port}`
const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
const errors = []
try {
  await fetch(`${base}/api/team/config`, { method: 'PUT', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ enabled: true }) })
  for (const role of (process.env.HOST_ONLY ? [] : ['developer', 'tester'])) {
    for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 960 }, extraHTTPHeaders: { 'x-forwarded-for': '192.0.2.10' } })
      const page = await context.newPage()
      page.on('pageerror', e => errors.push(e.message))
      await page.goto(base)
      await page.getByRole('radio', { name: role === 'developer' ? '研发 · 反馈开发进度' : '测试 · 提交问题与验收结果' }).check()
      await page.getByRole('button', { name: '确认角色并进入' }).click()
      await page.getByRole('button', { name: /查看版本/ }).click({ timeout: 10000 }).catch(async e => { console.log(await page.locator('body').innerText()); throw e })
      await page.locator('[data-version-no="v1.1"]').locator('..').getByRole('button', { name: '查看原型', exact: true }).click()
      await page.frameLocator('iframe').getByText('新版原型内容').waitFor()
      assert.ok(page.url().endsWith('/projects/navigation/versions/v1.1'))
      await page.getByRole('button', { name: '查看变更', exact: true }).click()
      await page.getByRole('tab', { name: /^变更/ }).waitFor()
      const action = role === 'developer' ? '反馈开发进度' : '提交测试问题'
      await page.getByRole('button', { name: action, exact: true }).first().click()
      await page.getByLabel('内容', { exact: true }).fill(`角色路径验证 ${role} ${width}`)
      await page.getByRole('button', { name: role === 'developer' ? '提交开发进度' : '提交测试问题', exact: true }).last().click()
      await page.getByText('记录已保存到主机').waitFor()
      assert.equal(await page.getByRole('button', { name: '设为当前基线', exact: true }).count(), 0)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
      await page.screenshot({ path: `.codex-ui-regression/screenshots/role-${role}-${width}.png`, fullPage: true })
      await page.reload()
      await page.getByRole('tab', { name: '团队协作' }).waitFor()
      await page.getByRole('button', { name: '返回 导航验证项目 的版本列表' }).click()
      await page.getByRole('button', { name: '查看当前基线原型' }).click()
      await page.frameLocator('iframe').getByText('基线原型内容').waitFor()
      await page.getByRole('button', { name: '返回 导航验证项目 的版本列表' }).click()
      await page.getByRole('textbox', { name: '搜索版本' }).fill('no-match')
      await page.getByRole('button', { name: '清除筛选' }).click()
      await page.locator('[data-version-no="v1.0"]').locator('..').getByRole('button', { name: '查看原型', exact: true }).focus()
      await page.keyboard.press('Enter')
      await page.frameLocator('iframe').getByText('基线原型内容').waitFor()
      await page.getByRole('button', { name: '返回 导航验证项目 的版本列表' }).click()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
      if (role === 'developer' && width === 1440) await page.screenshot({ path: '.codex-ui-regression/screenshots/project-prototype-path.png', fullPage: true })
      console.log(`${role} ${width}: project → version → prototype, reload, baseline, keyboard and filters passed`)
      await context.close()
    }
  }
  const page = await browser.newPage()
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(`${base}/#/projects`)
  await page.getByRole('link', { name: '查看 导航验证项目 的全部版本' }).waitFor()
  const cardBody = await page.locator('.fl-project-version-title').boundingBox()
  await page.mouse.click(cardBody.x + cardBody.width / 2, cardBody.y + cardBody.height / 2)
  await page.waitForURL('**/#/projects/navigation')
  await page.goBack()
  await page.getByRole('button', { name: '更多项目操作：导航验证项目' }).click()
  await page.getByRole('menuitem', { name: /编辑项目/ }).click()
  await page.getByRole('dialog').waitFor()
  assert.ok(page.url().endsWith('/projects'))
  await page.getByRole('button', { name: /Close|关闭/ }).click()
  await page.getByRole('button', { name: /继续处理/ }).click()
  await page.waitForURL('**/#/projects/navigation/versions/v1.1')
  await page.goBack()
  await page.getByRole('link', { name: '查看 导航验证项目 的全部版本' }).focus()
  await page.keyboard.press('Enter')
  await page.waitForURL('**/#/projects/navigation')
  await page.locator('[data-version-no="v1.1"]').click()
  await page.getByTestId('desktop-version-summary').getByRole('button', { name: /查看原型/ }).click()
  await page.frameLocator('iframe').getByText('新版原型内容').waitFor()
  console.log('product: card body and keyboard open versions; edit and continue remain independent; contextual preview opens; workbench preserved')
  assert.deepEqual(errors, [])
} finally {
  await browser.close()
  await server.close()
  cleanup(root)
}
